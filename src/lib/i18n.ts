/** Build the keyed lookup for a language (plain function, usable anywhere). */
export const translator = (lang: Language) => {
  const lookup = (l: Language, keys: string[]): string | undefined => {
    let current: unknown = translations[l];
    for (const k of keys) {
      if (current && typeof current === 'object' && k in (current as object)) {
        current = (current as Record<string, unknown>)[k];
      } else {
        return undefined;
      }
    }
    return typeof current === 'string' ? current : undefined;
  };

  const t = (path: string): string => {
    const keys = path.split('.');
    // Fall back to French when an Arabic string is missing.
    return lookup(lang, keys) ?? lookup('fr', keys) ?? path;
  };

  return { t };
};

/** Hook-style alias kept for existing screens. */
export const useTranslation = (lang: Language) => translator(lang);

/** Date/number locale for the current language. */
export const localeFor = (lang: Language): string => (lang === 'ar' ? 'ar-DZ' : 'fr-FR');

/**
 * Bilingual helper for inline strings: tr('Enregistrer', 'حفظ').
 * French is the default; Arabic is used when the UI is in Arabic.
 */
export const makeTr = (lang: Language) => (fr: string, ar: string): string => (lang === 'ar' ? ar : fr);

// ---------------------------------------------------------------------------
// Global current language — lets plain functions (toasts, print templates, lib
// helpers) translate too. AuthContext keeps it in sync, and the routes are
// re-mounted on a language change so every screen re-renders in the new one.
// ---------------------------------------------------------------------------
let currentLanguage: Language = 'fr';

export const setCurrentLanguage = (lang: Language) => { currentLanguage = lang; };
export const getCurrentLanguage = (): Language => currentLanguage;

/** tr('Enregistrer', 'حفظ') — French by default, Arabic when the UI is in Arabic. */
export const tr = (fr: string, ar: string): string => (currentLanguage === 'ar' ? ar : fr);
